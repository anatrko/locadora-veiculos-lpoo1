    @Override
    public void irPara(String tela) {
        for(Component c: container.getComponents()) {
            if(c.getName() != null && c.getName().equals(tela) && c instanceof Atualizavel a){
                a.aoExibir();
            }
        }
        cl.show(container, tela);
        // atualiza o tamanho de JFrame
        container.revalidate();
        this.pack();
    }
    
    private void adicionarTela(JPanel painel, String nome) {
        painel.setName(nome);
        container.add(painel, nome);
    }

